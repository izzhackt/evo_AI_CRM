import Foundation

/// Однополётный перезапускающийся затвор загрузки (review #912, medium).
///
/// Guard вида `if isLoading { return }` сам по себе МОЛЧА дропал
/// перезагрузку, пришедшую во время полёта, а завершение публиковало
/// результат СТАРЫХ фильтров без перепроверки: смена фильтра A→B в середине
/// сбора карты (до 12 последовательных RPC) оставляла пины A под чипами B
/// до ручного переключения представления.
///
/// Контракт:
/// - `invalidate()` — каждая смена фильтров двигает поколение: результат
///   любого полёта, начатого раньше, устарел;
/// - `run(_:)` — single-flight: второй вызов во время полёта не создаёт
///   параллельной загрузки (возврат false) — действующий полёт сам
///   перезапустится: публикация применяется только если поколение не
///   изменилось за время await, иначе попытка немедленно повторяется, и
///   `attempt` захватывает УЖЕ актуальные фильтры заново.
///
/// Выбор «generation counter», а не Task-cancellation: загрузки вью-модели
/// вызываются из нескольких мест (.task, refreshable, кнопки, debounce), и
/// отмена потребовала бы владения Task-handle'ами и разбора «кто отменил»;
/// счётчик оставляет записи однополётными, а почти завершённый старый сбор
/// честно завершается и немедленно перезапускается — проще для текущей
/// архитектуры async-методов (запись решения — по требованию review #912).
@MainActor
final class SingleFlightReloadGate {
    private(set) var generation = 0
    private(set) var isRunning = false

    /// Фильтры изменились: всё, что летит сейчас, обязано перезапуститься.
    func invalidate() {
        generation += 1
    }

    /// `attempt` сам читает актуальные фильтры при КАЖДОМ вызове, выполняет
    /// работу и возвращает замыкание-публикацию; публикуется только
    /// не-устаревший результат. Возврат false — полёт уже шёл, новый не
    /// создан (он перезапустится сам).
    @discardableResult
    func run(_ attempt: () async -> () -> Void) async -> Bool {
        if isRunning { return false }
        isRunning = true
        defer { isRunning = false }
        while true {
            let startedGeneration = generation
            let publish = await attempt()
            // Поколение сдвинулось за время await — результат старых
            // фильтров не публикуем и сразу пробуем заново с актуальными.
            if startedGeneration != generation { continue }
            publish()
            return true
        }
    }
}
