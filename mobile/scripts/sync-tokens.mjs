#!/usr/bin/env node
// Токены дизайна: <repo>/src/app/(portal)/portal.css -> src/theme/tokens.generated.ts.
// Источник один на веб и телефон. Запуск:
//   node scripts/sync-tokens.mjs           записать файл
//   node scripts/sync-tokens.mjs --check   упасть, если файл устарел (npm run check)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const mobileRoot = path.resolve(here, "..");
const cssPath = path.resolve(mobileRoot, "../src/app/(portal)/portal.css");
const outPath = path.join(mobileRoot, "src/theme/tokens.generated.ts");

/** Тело первого блока с данным селектором (по парным скобкам). */
function blockBody(css, selectorRegex, mustContain = "--pt-") {
  const re = new RegExp(selectorRegex, "gm");
  let match;
  while ((match = re.exec(css))) {
    let depth = 1;
    let i = match.index + match[0].length;
    const start = i;
    while (i < css.length && depth > 0) {
      if (css[i] === "{") depth += 1;
      else if (css[i] === "}") depth -= 1;
      i += 1;
    }
    const body = css.slice(start, i - 1);
    if (stripComments(body).includes(mustContain)) return body;
  }
  throw new Error(`portal.css: не найден блок ${selectorRegex}`);
}

function stripComments(text) {
  return text.replace(/\/\*[\s\S]*?\*\//g, "");
}

/** Объявления --pt-*: имя -> сырое значение. Без вложенных блоков. */
function declarations(body) {
  const out = new Map();
  for (const m of stripComments(body).matchAll(/(--pt-[a-z0-9-]+)\s*:\s*([^;]+);/g)) {
    out.set(m[1], m[2].replace(/\s+/g, " ").trim());
  }
  return out;
}

function resolve(value, scope, seen = new Set()) {
  let unresolved = false;
  const replaced = value.replace(/var\((--pt-[a-z0-9-]+)\)/g, (_, name) => {
    const next = scope.get(name);
    if (next === undefined || seen.has(name)) {
      unresolved = true;
      return "";
    }
    const inner = resolve(next, scope, new Set([...seen, name]));
    if (inner === null) unresolved = true;
    return inner ?? "";
  });
  return unresolved ? null : replaced;
}

function camel(name) {
  return name
    .replace(/^--pt-/, "")
    .replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
}

/** Что RN понимает как есть: цвета, числа, px/ms, тени, кривые. Градиенты, url, calc, шрифты через var пропускаем. */
function convert(value) {
  if (value === null) return undefined;
  if (/url\(|gradient|calc\(|^light$|^dark$/.test(value)) return undefined;
  if (/^-?\d+(\.\d+)?px$/.test(value)) return Number.parseFloat(value);
  if (/^-?\d+(\.\d+)?ms$/.test(value)) return Number.parseFloat(value);
  if (/^-?\d+(\.\d+)?$/.test(value)) return Number.parseFloat(value);
  return value;
}

function table(scope, names) {
  const out = {};
  for (const name of [...names].sort()) {
    const converted = convert(resolve(scope.get(name), scope));
    if (converted !== undefined) out[camel(name)] = converted;
  }
  return out;
}

export function buildSource(css) {
  const light = declarations(blockBody(css, String.raw`^\.pt-shell \{`));
  const darkOverrides = declarations(blockBody(css, String.raw`^:root\[data-theme="dark"\] \.pt-shell \{`));
  const dark = new Map([...light, ...darkOverrides]);
  // Тёмное меню (телефон): те же токены, что у рейла, в обеих темах.
  const menuOverrides = declarations(blockBody(css, String.raw`\.pt-nav-menu \{`, "--pt-rail-group"));
  const menu = new Map([...light, ...menuOverrides]);

  // Шрифты задаёт src/theme/fonts.ts (в вебе это var(--font-*) от next/font).
  const names = new Set([...light.keys()].filter((n) => !n.startsWith("--pt-font-")));
  const menuNames = new Set([...menuOverrides.keys()]);
  const render = (title, obj) => `export const ${title} = ${JSON.stringify(obj, null, 2)} as const;\n`;
  return [
    "// GENERATED by scripts/sync-tokens.mjs from src/app/(portal)/portal.css. Do not edit.",
    "// Обновить: npm run sync-tokens. Проверка актуальности: npm run check.",
    "",
    render("lightTokens", table(light, names)),
    render("darkTokens", table(dark, names)),
    "// Тёмное меню ☰ и рейл: накладываются поверх активной темы.",
    render("menuTokens", table(menu, menuNames)),
    "export type TokenSet = typeof lightTokens;",
    "",
  ].join("\n");
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const source = buildSource(readFileSync(cssPath, "utf8"));
  if (process.argv.includes("--check")) {
    const current = existsSync(outPath) ? readFileSync(outPath, "utf8") : "";
    if (current !== source) {
      console.error("tokens.generated.ts устарел: выполните `npm run sync-tokens` в mobile/.");
      process.exit(1);
    }
    console.log("tokens.generated.ts актуален.");
  } else {
    writeFileSync(outPath, source);
    console.log(`Записан ${path.relative(mobileRoot, outPath)}`);
  }
}
