// Переходы внутри раздела CSCA, общие для экранов. «К темам» ведёт к вкладке «Занятия» (темы программы): на вебе ссылка
// `/portal/csca` открывает «Об экзамене», потому что вкладка по умолчанию там обзор, но слово «темам» обещает именно темы.
import { router } from "expo-router";

/** Куда вести «назад», когда стека нет (ссылка, перезапуск): к «Занятиям». */
export const CSCA_TOPICS_FALLBACK = "/csca?view=lessons";

/**
 * «К темам»: вернуться к главной раздела на вкладке «Занятия». `dismissTo` разворачивает стек до уже открытой главной (а не
 * кладёт вторую копию поверх урока или теста) и меняет её параметр; если главной в стеке нет, заменяет текущий экран ею.
 */
export function openCscaTopics(): void {
  router.dismissTo({ pathname: "/csca", params: { view: "lessons" } });
}
