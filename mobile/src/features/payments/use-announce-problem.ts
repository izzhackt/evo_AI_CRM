// Причина отказа (чек не ушёл, файл не подошёл, камера запрещена) появляется под кнопкой, а фокус читалки остаётся на самой кнопке:
// без объявления студент, который не видит экран, не узнает, что чек не отправлен. Успех объявляется отдельно, его сообщение заменяет
// кнопку. На iPhone объявление встаёт в очередь за тем, что читалка уже говорит («Сохранить, кнопка»), и не обрывает его.
import { useEffect } from "react";

import { announce } from "@/ui/a11y";

/**
 * Объявляет `problem` каждый раз, когда случается отказ, а не только когда меняется текст: студент нажал «Сохранить» ещё раз и снова
 * получил тот же отказ (проверка до отправки не доходит до сети, текст тот же) - он должен это услышать. Поэтому событие отказа передаётся
 * отдельно: `failure` - состояние ошибки у отправки (новый объект при каждом отказе), `noticeSeq` - счётчик отказов выбора файла.
 * Повтор того же текста быстрее чем за 0,8 с `announce` склеивает сам (двойной вызов эффекта).
 */
export function useAnnounceProblem(problem: string | null, failure: unknown, noticeSeq: number): void {
  useEffect(() => {
    if (problem) announce(problem, { queue: true });
  }, [problem, failure, noticeSeq]);
}
