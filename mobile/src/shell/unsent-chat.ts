// Что в беседе с командой ещё не отправлено: набранный черновик, сообщение в пути и сообщение, которое не ушло («Повторить»). Всё это
// живёт в самом экране беседы. Сброс стека «Входящих» при уходе с вкладки (`inbox-stack.ts`) экран размонтирует, и набранное пропало
// бы (разбор ревью #1590: «Написать EVO» с «Главной» кладёт в стек одну беседу, студент начал письмо и ушёл на другую вкладку). Поэтому
// стек, в котором беседа держит неотправленное, не сбрасывается: вкладка помнит его, как и раньше. Беседа без черновика и очереди
// сбрасывается к списку, как решено в D2.
// Признак привязан к КАБИНЕТУ (его кэш чтений - `QueryClient`, он создаётся заново при каждом входе, как в `read-failures.ts`) и снимается,
// когда беседа закрывается: другой студент на том же устройстве ни чужого черновика, ни чужого признака не увидит.
import { useQueryClient, type QueryClient } from "@tanstack/react-query";
import { useEffect } from "react";

const holding = new WeakSet<QueryClient>();

/** Держит ли открытая беседа этого кабинета неотправленное (тогда стек «Входящих» с ней не сбрасывается). */
export function hasUnsentChat(session: QueryClient): boolean {
  return holding.has(session);
}

/** Беседа сообщает, есть ли у неё неотправленное; закрываясь (или когда неотправленного не стало), снимает признак. */
export function useReportUnsentChat(unsent: boolean): void {
  const session = useQueryClient();
  useEffect(() => {
    if (!unsent) return undefined;
    holding.add(session);
    return () => {
      holding.delete(session);
    };
  }, [session, unsent]);
}
