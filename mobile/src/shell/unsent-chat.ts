// Что в беседе с командой ещё не отправлено: набранный черновик, сообщение в пути и сообщение, которое не ушло («Повторить»). Всё это
// живёт в самом экране беседы. Сброс стека «Входящих» (`inbox-stack.ts`) экран размонтирует, и набранное пропало бы: при уходе с вкладки
// (разбор ревью #1590: «Написать EVO» с «Главной» кладёт в стек одну беседу, студент начал письмо и ушёл на другую вкладку) и при нажатии на
// уже открытую вкладку «Входящие» (лента или список поверх беседы с черновиком). Поэтому стек, в котором беседа держит неотправленное,
// не сбрасывается ни там, ни там: как на main, вкладка помнит его, а нажатие на открытую вкладку ничего не делает. Беседа без черновика и
// очереди сбрасывается к списку, как решено в D2.
// Признак привязан к КАБИНЕТУ (его кэш чтений - `QueryClient`, он создаётся заново при каждом входе, как в `read-failures.ts`) и снимается,
// когда беседа закрывается: другой студент на том же устройстве ни чужого черновика, ни чужого признака не увидит.
import { useQueryClient, type QueryClient } from "@tanstack/react-query";
import { useEffect } from "react";

// Бесед в стеке может быть несколько (☰ «Входящие», затем строка беседы в списке кладёт вторую поверх первой: `[беседа, список, беседа]`),
// поэтому признак - СЧЁТЧИК беседы с неотправленным, а не да/нет: вторая беседа, где написали и стёрли или отправили, не снимает признак
// первой, у которой черновик остался.
const holding = new WeakMap<QueryClient, number>();

/** Держит ли хоть одна открытая беседа этого кабинета неотправленное (тогда стек «Входящих» с ней не сбрасывается). */
export function hasUnsentChat(session: QueryClient): boolean {
  return (holding.get(session) ?? 0) > 0;
}

/** Беседа сообщает, есть ли у неё неотправленное; закрываясь (или когда неотправленного не стало), снимает свою долю признака. */
export function useReportUnsentChat(unsent: boolean): void {
  const session = useQueryClient();
  useEffect(() => {
    if (!unsent) return undefined;
    holding.set(session, (holding.get(session) ?? 0) + 1);
    return () => {
      const left = (holding.get(session) ?? 1) - 1;
      if (left > 0) holding.set(session, left);
      else holding.delete(session);
    };
  }, [session, unsent]);
}
