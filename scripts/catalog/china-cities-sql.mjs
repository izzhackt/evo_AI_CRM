#!/usr/bin/env node
/**
 * Китай 2026-11: карточки новых городов и связь вузов с ними одной транзакцией SQL (план
 * docs/catalog/china-2026-11-plan.md, срез C5). Вторая часть после china-universities-sql.mjs: вузы уже опубликованы.
 *
 *   node scripts/catalog/china-cities-sql.mjs [--commit] [--actor-membership UUID] [--seed-dir DIR] > china-cities.sql
 *
 * Скрипт ничего не выполняет: он печатает SQL. Без --commit транзакция заканчивается ROLLBACK (сухой прогон, в конце
 * печатается отчёт). С --commit заканчивается COMMIT. Запуск на production тем же способом, что у china-universities-sql.mjs.
 *
 * Входы: scripts/catalog/data/china-2026-11/geography-seed/ (cities.json, photos-manifest.json, photos/) в формате сида
 * 283 (проверка loadGeographySeed: те же правила текста, ссылок и фото), scripts/catalog/data/china-2026-11/city-links-new.json
 * (карточка вуза → ключ нового города). Фото сначала загружаются в бакет portal-university-photos существующим
 * upload-geography-photos.mjs с `--seed-dir` этой папки (--plan, --check, --apply): RPC публикации города отказывает,
 * пока файла нет в бакете.
 *
 * Что делает SQL (теми же RPC, что редактор «География» в CRM, от имени действующего системного Admin):
 *   1. города: отсутствует: staff_catalog_city_upsert_v1 (версия 0) и staff_catalog_city_publish_v1; есть и равен входу:
 *      пропуск; отличается: правка по текущей версии и публикация;
 *   2. staff_catalog_institution_city_set_v1: каждый вуз списка (по названию и стране) связывается со своим городом,
 *      если у него нет связи (существующая связь не перезаписывается: вузы, уже имевшие город, не трогаются).
 * Повтор ничего не дублирует: request_id выводятся из содержимого и версии, неизменное пропускается.
 */
import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { loadGeographySeed } from "./geography-seed-lib.mjs";
import { ORGANIZATION_ID } from "./malaysia-universities-sql.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const DATA = resolve(ROOT, "scripts/catalog/data/china-2026-11");
export const DEFAULT_SEED_DIR = resolve(DATA, "geography-seed");
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/u;
const REQUEST_PREFIX = "evo-cn-2611-city";

const dollar = (value, tag) => {
  const text = typeof value === "string" ? value : JSON.stringify(value);
  if (text.includes(`$${tag}$`)) throw new Error(`dollar tag ${tag} occurs in data`);
  return `$${tag}$${text}$${tag}$`;
};

export function buildCitiesSql({ commit = false, actorMembership = null, seedDir = DEFAULT_SEED_DIR } = {}) {
  if (actorMembership !== null && !UUID.test(actorMembership)) throw new Error("--actor-membership must be a UUID");
  const seed = loadGeographySeed({ seedDir, allowMissing: true });
  const cards = JSON.parse(readFileSync(resolve(ROOT, "src/lib/server/university-catalog-reviewed-china.json"), "utf8"));
  const links = JSON.parse(readFileSync(resolve(DATA, "city-links-new.json"), "utf8"));
  const cardByKey = new Map(cards.map((card) => [card.key, card]));
  const cityKeys = new Set(seed.cities.map((city) => city.key));
  for (const city of seed.cities) {
    if (city.country !== "CN") throw new Error(`city ${city.key} is not in CN`);
    if (city.status !== "published" || city.photo === null) throw new Error(`city ${city.key} must be published with a photo`);
  }
  const used = new Set();
  for (const [cardKey, cityKey] of Object.entries(links)) {
    if (!cardByKey.has(cardKey)) throw new Error(`link for unknown card ${cardKey}`);
    if (!cityKeys.has(cityKey)) throw new Error(`card ${cardKey} points to city ${cityKey} that is not in the seed`);
    used.add(cityKey);
  }
  for (const key of cityKeys) if (!used.has(key)) throw new Error(`city ${key} has no university link`);
  const cityRows = seed.cities.map((city, index) => ({
    ord: index + 1, payload: Object.fromEntries(Object.entries(city).filter(([name]) => name !== "status")),
  }));
  const linkRows = Object.entries(links).map(([cardKey, cityKey], index) => {
    const card = cardByKey.get(cardKey);
    return { ord: index + 1, cardKey, cityKey, institutionName: card.content.name, country: card.content.country };
  });
  const lines = [];
  const out = (text) => lines.push(text);
  out("\\set ON_ERROR_STOP on");
  out("-- China 2026-11: new city cards and institution links. Generated by scripts/catalog/china-cities-sql.mjs.");
  out("BEGIN;");
  out("SET LOCAL statement_timeout = '300s';");
  out("CREATE TEMP TABLE a_cities (ord INT PRIMARY KEY, city JSONB NOT NULL);");
  for (const row of cityRows) out(`INSERT INTO a_cities VALUES (${row.ord}, ${dollar(row.payload, "c")}::jsonb);`);
  out("CREATE TEMP TABLE a_links (ord INT PRIMARY KEY, card_key TEXT NOT NULL, city_key TEXT NOT NULL, institution_name TEXT NOT NULL, country TEXT NOT NULL);");
  for (const row of linkRows) {
    out(`INSERT INTO a_links VALUES (${row.ord}, ${dollar(row.cardKey, "k")}, ${dollar(row.cityKey, "y")}, ${dollar(row.institutionName, "n")}, ${dollar(row.country, "o")});`);
  }
  out("CREATE TEMP TABLE a_city_report (ord INT, key TEXT, state TEXT, version_after BIGINT, city_status TEXT);");
  out("CREATE TEMP TABLE a_link_report (ord INT, card_key TEXT, city_key TEXT, state TEXT);");
  out(`SELECT ${actorMembership ? `'${actorMembership}'::uuid` : "m.id"} AS actor_membership, p.auth_user_id AS actor_sub`);
  out("FROM platform.organization_memberships m JOIN platform.profiles p ON p.id = m.profile_id");
  out(`WHERE m.organization_id = '${ORGANIZATION_ID}' AND m.status = 'active' AND p.status = 'active' AND m.is_system_admin`);
  if (actorMembership) out(`  AND m.id = '${actorMembership}'`);
  out("ORDER BY m.created_at LIMIT 1 \\gset");
  out(`SELECT set_config('request.jwt.claims', json_build_object('sub', :'actor_sub', 'role', 'authenticated',
  'platform_membership_id', :'actor_membership', 'platform_organization_id', '${ORGANIZATION_ID}')::text, TRUE) \\g /dev/null`);
  out("SELECT set_config('request.jwt.claim.sub', :'actor_sub', TRUE) \\g /dev/null");
  out(`DO $run$
DECLARE
  org CONSTANT UUID := '${ORGANIZATION_ID}';
  r RECORD; l RECORD; ex platform.catalog_cities%ROWTYPE; inst UUID; ver BIGINT; st TEXT; digest TEXT; link TEXT; same BOOLEAN; v_status TEXT;
BEGIN
  FOR r IN SELECT * FROM a_cities ORDER BY ord LOOP
    digest := encode(sha256(convert_to(r.city::TEXT, 'UTF8')), 'hex');
    SELECT * INTO ex FROM platform.catalog_cities c WHERE c.organization_id = org AND c.city_key = r.city ->> 'key';
    IF NOT FOUND THEN
      st := 'new'; ver := 0;
    ELSE
      ver := ex.version;
      same := ex.country_code = r.city ->> 'country' AND ex.name_ru = r.city ->> 'nameRu' AND ex.name_ky = r.city ->> 'nameKy'
        AND ex.name_en = r.city ->> 'nameEn' AND ex.lat IS NOT DISTINCT FROM (r.city ->> 'lat')::DOUBLE PRECISION
        AND ex.lng IS NOT DISTINCT FROM (r.city ->> 'lng')::DOUBLE PRECISION AND ex.photo IS NOT DISTINCT FROM (r.city -> 'photo')
        AND ex.summary_ru IS NOT DISTINCT FROM r.city ->> 'summaryRu' AND ex.summary_ky IS NOT DISTINCT FROM r.city ->> 'summaryKy'
        AND ex.fact_ru IS NOT DISTINCT FROM r.city ->> 'factRu' AND ex.fact_ky IS NOT DISTINCT FROM r.city ->> 'factKy'
        AND ex.fact_source_url IS NOT DISTINCT FROM r.city ->> 'factSourceUrl'
        AND ex.fact_verified_on IS NOT DISTINCT FROM (r.city ->> 'factVerifiedOn')::DATE AND ex.ky_review = r.city ->> 'kyReview';
      st := CASE WHEN same THEN 'current' ELSE 'update' END;
    END IF;
    IF st <> 'current' THEN
      EXECUTE 'SET LOCAL ROLE authenticated';
      PERFORM platform.staff_catalog_city_upsert_v1(org, r.city, ver,
        md5('${REQUEST_PREFIX}:' || (r.city ->> 'key') || ':' || ver || ':' || digest || ':upsert')::UUID);
      EXECUTE 'RESET ROLE';
    END IF;
    SELECT c.status, c.version INTO v_status, ver FROM platform.catalog_cities c WHERE c.organization_id = org AND c.city_key = r.city ->> 'key';
    IF v_status <> 'published' THEN
      EXECUTE 'SET LOCAL ROLE authenticated';
      PERFORM platform.staff_catalog_city_publish_v1(org, r.city ->> 'key', TRUE, ver,
        md5('${REQUEST_PREFIX}:' || (r.city ->> 'key') || ':' || ver || ':' || digest || ':publish')::UUID);
      EXECUTE 'RESET ROLE';
      IF st = 'current' THEN st := 'publish'; END IF;
    END IF;
    INSERT INTO a_city_report
      SELECT r.ord, r.city ->> 'key', st, c.version, c.status
      FROM platform.catalog_cities c WHERE c.organization_id = org AND c.city_key = r.city ->> 'key';
  END LOOP;
  FOR l IN SELECT * FROM a_links ORDER BY ord LOOP
    SELECT i.id INTO inst FROM platform.catalog_institutions i
    WHERE i.organization_id = org AND i.institution_kind = 'university' AND i.country_code = l.country
      AND platform_private.normalize_catalog_institution_name(i.institution_name) = platform_private.normalize_catalog_institution_name(l.institution_name);
    IF inst IS NULL THEN RAISE EXCEPTION 'institution % is not published yet: run the catalog import first', l.institution_name; END IF;
    SELECT x.city_key INTO link FROM platform.catalog_institution_cities x WHERE x.institution_id = inst;
    IF link IS NULL THEN
      EXECUTE 'SET LOCAL ROLE authenticated';
      PERFORM platform.staff_catalog_institution_city_set_v1(org, inst, l.city_key,
        md5('${REQUEST_PREFIX}:' || l.card_key || ':link:' || l.city_key)::UUID);
      EXECUTE 'RESET ROLE';
      INSERT INTO a_link_report VALUES (l.ord, l.card_key, l.city_key, 'set');
    ELSIF link = l.city_key THEN
      INSERT INTO a_link_report VALUES (l.ord, l.card_key, l.city_key, 'current');
    ELSE
      INSERT INTO a_link_report VALUES (l.ord, l.card_key, link, 'kept_other_city');
    END IF;
  END LOOP;
END
$run$;`);
  out("SELECT 'CITY', key, state, version_after, city_status FROM a_city_report ORDER BY ord;");
  out("SELECT 'LINK', card_key, city_key, state FROM a_link_report ORDER BY ord;");
  out("SELECT 'SUMMARY_LINKS', count(*) FILTER (WHERE state = 'set'), count(*) FILTER (WHERE state = 'current'), count(*) FILTER (WHERE state = 'kept_other_city') FROM a_link_report;");
  out(`SELECT 'CN_CITIES_PUBLISHED', count(*) FROM platform.catalog_cities WHERE organization_id = '${ORGANIZATION_ID}' AND country_code = 'CN' AND status = 'published';`);
  out(`SELECT 'CN_INSTITUTIONS_WITHOUT_CITY', count(*) FROM platform.catalog_institutions i WHERE i.organization_id = '${ORGANIZATION_ID}' AND i.country_code = 'CN'
  AND NOT EXISTS (SELECT 1 FROM platform.catalog_institution_cities l WHERE l.institution_id = i.id);`);
  out(commit ? "COMMIT;" : "ROLLBACK;");
  return { sql: `${lines.join("\n")}\n`, cities: cityRows.length, links: linkRows.length };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  let commit = false, actorMembership = null, seedDir = DEFAULT_SEED_DIR;
  for (let index = 0; index < args.length; index += 1) {
    if (args[index] === "--commit") commit = true;
    else if (args[index] === "--actor-membership") actorMembership = args[++index] ?? null;
    else if (args[index] === "--seed-dir") seedDir = resolve(args[++index] ?? "");
    else { process.stderr.write("Usage: node scripts/catalog/china-cities-sql.mjs [--commit] [--actor-membership UUID] [--seed-dir DIR]\n"); process.exit(1); }
  }
  const result = buildCitiesSql({ commit, actorMembership, seedDir });
  process.stderr.write(`${JSON.stringify({ mode: commit ? "COMMIT" : "ROLLBACK (dry run)", cities: result.cities, links: result.links })}\n`);
  process.stdout.write(result.sql);
}
