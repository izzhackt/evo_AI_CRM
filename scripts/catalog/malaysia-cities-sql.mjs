#!/usr/bin/env node
/**
 * Малайзия 2026-11: две новые карточки городов (Пенанг, Кота-Кинабалу) и связь вузов с ними одной транзакцией SQL.
 *
 *   node scripts/catalog/malaysia-cities-sql.mjs [--commit] [--actor-membership UUID] [--seed-dir DIR] > cities.sql
 *
 * Скрипт ничего не выполняет: он печатает SQL. Без --commit транзакция заканчивается ROLLBACK (сухой прогон, в конце
 * печатается отчёт). С --commit заканчивается COMMIT. Запуск на production (self-hosted Supabase) тем же способом, что
 * scripts/catalog/malaysia-universities-sql.mjs:
 *
 *   ssh hermes-vps 'docker exec -i evo-supabase-db psql -U postgres -d postgres -X -q -At -F "	" -v ON_ERROR_STOP=1' < cities.sql
 *
 * Входы: scripts/catalog/data/malaysia-2026-11/geography-seed/ (cities.json, photos-manifest.json, photos/) в том же
 * формате, что сид 283 (проверка loadGeographySeed из geography-seed-lib.mjs, те же правила текста, ссылок и фото).
 * Фото сначала загружаются в бакет portal-university-photos существующим upload-geography-photos.mjs с
 * `--seed-dir` этой папки (--plan, --check, --apply): RPC публикации города отказывает, пока файла нет в бакете.
 *
 * Что делает SQL (теми же RPC, что редактор «География» в CRM, от имени действующего системного Admin):
 *   1. город отсутствует: staff_catalog_city_upsert_v1 (версия 0) и staff_catalog_city_publish_v1;
 *      город есть и равен входу: пропуск; отличается: правка по текущей версии и публикация;
 *   2. staff_catalog_institution_city_set_v1: вуз (по названию и стране) связывается с городом, если связь другая.
 * Повтор ничего не дублирует: request_id выводятся из содержимого и версии, неизменное пропускается.
 */
import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { loadGeographySeed } from "./geography-seed-lib.mjs";
import { ORGANIZATION_ID } from "./malaysia-universities-sql.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
export const DEFAULT_SEED_DIR = resolve(ROOT, "scripts/catalog/data/malaysia-2026-11/geography-seed");
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/u;

/** Город → карточка вуза (ключ reviewed-JSON), которая к нему привязывается. */
export const CITY_INSTITUTIONS = Object.freeze({ penang: "inti-penang", "kota-kinabalu": "inti-sabah" });

const dollar = (value, tag) => {
  const text = typeof value === "string" ? value : JSON.stringify(value);
  if (text.includes(`$${tag}$`)) throw new Error(`dollar tag ${tag} occurs in data`);
  return `$${tag}$${text}$${tag}$`;
};

export function buildCitiesSql({ commit = false, actorMembership = null, seedDir = DEFAULT_SEED_DIR } = {}) {
  if (actorMembership !== null && !UUID.test(actorMembership)) throw new Error("--actor-membership must be a UUID");
  const seed = loadGeographySeed({ seedDir, allowMissing: true });
  const cards = JSON.parse(readFileSync(resolve(ROOT, "src/lib/server/university-catalog-reviewed-malaysia.json"), "utf8"));
  const cityKeys = new Set(seed.cities.map((city) => city.key));
  for (const key of Object.keys(CITY_INSTITUTIONS)) if (!cityKeys.has(key)) throw new Error(`city ${key} is missing in the seed`);
  for (const city of seed.cities) {
    if (city.country !== "MY") throw new Error(`city ${city.key} is not in MY`);
    if (!Object.hasOwn(CITY_INSTITUTIONS, city.key)) throw new Error(`city ${city.key} has no institution link`);
    if (city.status !== "published" || city.photo === null) throw new Error(`city ${city.key} must be published with a photo`);
  }
  const rows = seed.cities.map((city, index) => {
    const card = cards.find((item) => item.key === CITY_INSTITUTIONS[city.key]);
    if (!card) throw new Error(`unknown card ${CITY_INSTITUTIONS[city.key]}`);
    const payload = Object.fromEntries(Object.entries(city).filter(([name]) => name !== "status"));
    return { ord: index + 1, payload, institutionName: card.content.name, country: card.content.country };
  });
  const lines = [];
  const out = (text) => lines.push(text);
  out("\\set ON_ERROR_STOP on");
  out("-- Malaysia 2026-11: city cards Penang and Kota Kinabalu and institution links. Generated by scripts/catalog/malaysia-cities-sql.mjs.");
  out("BEGIN;");
  out("SET LOCAL statement_timeout = '120s';");
  out("CREATE TEMP TABLE a_cities (ord INT PRIMARY KEY, city JSONB NOT NULL, institution_name TEXT NOT NULL, country TEXT NOT NULL);");
  for (const row of rows) {
    out(`INSERT INTO a_cities VALUES (${row.ord}, ${dollar(row.payload, "c")}::jsonb, ${dollar(row.institutionName, "n")}, ${dollar(row.country, "k")});`);
  }
  out("CREATE TEMP TABLE a_city_report (ord INT, key TEXT, state TEXT, version_before BIGINT, version_after BIGINT, city_status TEXT, city_link TEXT);");
  out(`SELECT ${actorMembership ? `'${actorMembership}'::uuid` : "m.id"} AS actor_membership, p.auth_user_id AS actor_sub`);
  out("FROM platform.organization_memberships m JOIN platform.profiles p ON p.id = m.profile_id");
  out(`WHERE m.organization_id = '${ORGANIZATION_ID}' AND m.status = 'active' AND p.status = 'active' AND m.is_system_admin`);
  if (actorMembership) out(`  AND m.id = '${actorMembership}'`);
  out("ORDER BY m.created_at LIMIT 1 \\gset");
  out(`SELECT set_config('request.jwt.claims', json_build_object('sub', :'actor_sub', 'role', 'authenticated',
  'platform_membership_id', :'actor_membership', 'platform_organization_id', '${ORGANIZATION_ID}')::text, TRUE) \\g /dev/null`);
  out("SELECT set_config('request.jwt.claim.sub', :'actor_sub', TRUE) \\g /dev/null");
  out(`DO $run$
DECLARE
  org CONSTANT UUID := '${ORGANIZATION_ID}';
  r RECORD; ex platform.catalog_cities%ROWTYPE; inst UUID; ver BIGINT; st TEXT; digest TEXT; link TEXT; same BOOLEAN; v_status TEXT;
BEGIN
  FOR r IN SELECT * FROM a_cities ORDER BY ord LOOP
    digest := encode(sha256(convert_to(r.city::TEXT, 'UTF8')), 'hex');
    SELECT * INTO ex FROM platform.catalog_cities c WHERE c.organization_id = org AND c.city_key = r.city ->> 'key';
    IF NOT FOUND THEN
      st := 'new'; ver := 0;
    ELSE
      ver := ex.version;
      same := ex.country_code = r.city ->> 'country' AND ex.name_ru = r.city ->> 'nameRu' AND ex.name_ky = r.city ->> 'nameKy'
        AND ex.name_en = r.city ->> 'nameEn' AND ex.lat IS NOT DISTINCT FROM (r.city ->> 'lat')::DOUBLE PRECISION
        AND ex.lng IS NOT DISTINCT FROM (r.city ->> 'lng')::DOUBLE PRECISION AND ex.photo IS NOT DISTINCT FROM (r.city -> 'photo')
        AND ex.summary_ru IS NOT DISTINCT FROM r.city ->> 'summaryRu' AND ex.summary_ky IS NOT DISTINCT FROM r.city ->> 'summaryKy'
        AND ex.fact_ru IS NOT DISTINCT FROM r.city ->> 'factRu' AND ex.fact_ky IS NOT DISTINCT FROM r.city ->> 'factKy'
        AND ex.fact_source_url IS NOT DISTINCT FROM r.city ->> 'factSourceUrl'
        AND ex.fact_verified_on IS NOT DISTINCT FROM (r.city ->> 'factVerifiedOn')::DATE AND ex.ky_review = r.city ->> 'kyReview';
      st := CASE WHEN same THEN 'current' ELSE 'update' END;
    END IF;
    IF st <> 'current' THEN
      EXECUTE 'SET LOCAL ROLE authenticated';
      PERFORM platform.staff_catalog_city_upsert_v1(org, r.city, ver,
        md5('evo-my-2611-city:' || (r.city ->> 'key') || ':' || ver || ':' || digest || ':upsert')::UUID);
      EXECUTE 'RESET ROLE';
    END IF;
    SELECT c.status, c.version INTO v_status, ver FROM platform.catalog_cities c WHERE c.organization_id = org AND c.city_key = r.city ->> 'key';
    IF v_status <> 'published' THEN
      EXECUTE 'SET LOCAL ROLE authenticated';
      PERFORM platform.staff_catalog_city_publish_v1(org, r.city ->> 'key', TRUE, ver,
        md5('evo-my-2611-city:' || (r.city ->> 'key') || ':' || ver || ':' || digest || ':publish')::UUID);
      EXECUTE 'RESET ROLE';
      IF st = 'current' THEN st := 'publish'; END IF;
    END IF;
    SELECT i.id INTO inst FROM platform.catalog_institutions i
    WHERE i.organization_id = org AND i.institution_kind = 'university' AND i.country_code = r.country
      AND platform_private.normalize_catalog_institution_name(i.institution_name) = platform_private.normalize_catalog_institution_name(r.institution_name);
    IF inst IS NULL THEN RAISE EXCEPTION 'institution % is not published yet: run the catalog import first', r.institution_name; END IF;
    SELECT l.city_key INTO link FROM platform.catalog_institution_cities l WHERE l.institution_id = inst;
    IF link IS DISTINCT FROM r.city ->> 'key' THEN
      EXECUTE 'SET LOCAL ROLE authenticated';
      PERFORM platform.staff_catalog_institution_city_set_v1(org, inst, r.city ->> 'key',
        md5('evo-my-2611-city:' || (r.city ->> 'key') || ':link:' || inst::TEXT)::UUID);
      EXECUTE 'RESET ROLE';
      link := (r.city ->> 'key') || ' (set)';
    END IF;
    INSERT INTO a_city_report
      SELECT r.ord, r.city ->> 'key', st, CASE WHEN st = 'new' THEN 0 ELSE ex.version END, c.version, c.status, link
      FROM platform.catalog_cities c WHERE c.organization_id = org AND c.city_key = r.city ->> 'key';
  END LOOP;
END
$run$;`);
  out("SELECT 'CITY', key, state, version_before, version_after, city_status, city_link FROM a_city_report ORDER BY ord;");
  out(`SELECT 'MY_CITIES_PUBLISHED', count(*) FROM platform.catalog_cities WHERE organization_id = '${ORGANIZATION_ID}' AND country_code = 'MY' AND status = 'published';`);
  out(`SELECT 'MY_INSTITUTIONS_WITHOUT_CITY', count(*) FROM platform.catalog_institutions i WHERE i.organization_id = '${ORGANIZATION_ID}' AND i.country_code = 'MY'
  AND NOT EXISTS (SELECT 1 FROM platform.catalog_institution_cities l WHERE l.institution_id = i.id);`);
  out(commit ? "COMMIT;" : "ROLLBACK;");
  return { sql: `${lines.join("\n")}\n`, cities: rows.length };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  let commit = false, actorMembership = null, seedDir = DEFAULT_SEED_DIR;
  for (let index = 0; index < args.length; index += 1) {
    if (args[index] === "--commit") commit = true;
    else if (args[index] === "--actor-membership") actorMembership = args[++index] ?? null;
    else if (args[index] === "--seed-dir") seedDir = resolve(args[++index] ?? "");
    else { process.stderr.write("Usage: node scripts/catalog/malaysia-cities-sql.mjs [--commit] [--actor-membership UUID] [--seed-dir DIR]\n"); process.exit(1); }
  }
  const result = buildCitiesSql({ commit, actorMembership, seedDir });
  process.stderr.write(`${JSON.stringify({ mode: commit ? "COMMIT" : "ROLLBACK (dry run)", cities: result.cities })}\n`);
  process.stdout.write(result.sql);
}
