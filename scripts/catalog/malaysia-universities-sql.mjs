#!/usr/bin/env node
/**
 * Малайзия 2026-11: карточки университетов, привязка городов и стоимость программ одной транзакцией SQL.
 *
 *   node scripts/catalog/malaysia-universities-sql.mjs [--commit] [--actor-membership UUID] [--skip-costs] [--simulate-352] > malaysia.sql
 *
 * Скрипт ничего не выполняет: он печатает SQL. Без --commit транзакция заканчивается ROLLBACK (сухой прогон,
 * в конце печатается отчёт). С --commit заканчивается COMMIT. Запуск на production (self-hosted Supabase):
 *
 *   ssh hermes-vps 'docker exec -i evo-supabase-db psql -U postgres -d postgres -X -q -At -F "	" -v ON_ERROR_STOP=1' < malaysia.sql
 *
 * Что делает SQL (все записи теми же RPC, что и Admin-публикация в CRM, от имени действующего системного Admin):
 *   1. src/lib/server/university-catalog-reviewed-malaysia.json: для каждой карточки находит вуз по названию и стране;
 *      нет: публикует новой карточкой (stage + review), отличается от опубликованной: новая версия, равна: пропуск;
 *   2. scripts/catalog/data/malaysia-2026-11/city-links.json: связывает новые карточки с существующими городами
 *      (staff_catalog_institution_city_set_v1), если связь другая;
 *   3. scripts/catalog/data/malaysia-2026-11/programme-costs.json: строки стоимости программ через
 *      staff_catalog_cost_import_v1 (формат и проверки import-catalog-costs.mjs; строка с тем же importKey не
 *      создаётся второй раз, поэтому повтор безопасен).
 * Повтор тем же файлом ничего не дублирует: неизменные карточки пропускаются, request_id выводятся из содержимого.
 * Предел программ в карточке (300) требует миграции 352 на этой базе: для сухого прогона до неё есть --simulate-352
 * (та же замена одного фрагмента, внутри транзакции и с ROLLBACK; вместе с --commit запрещён).
 */
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { planImport } from "./import-catalog-costs.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const DATA = resolve(ROOT, "scripts/catalog/data/malaysia-2026-11");
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/u;
export const ORGANIZATION_ID = "2b527337-3dfe-4c00-b9f5-002a2bccfd29";

const dollar = (value, tag) => {
  const text = typeof value === "string" ? value : JSON.stringify(value);
  if (text.includes(`$${tag}$`)) throw new Error(`dollar tag ${tag} occurs in data`);
  return `$${tag}$${text}$${tag}$`;
};

export function buildSql({ commit = false, actorMembership = null, skipCosts = false, simulate352 = false } = {}) {
  if (commit && simulate352) throw new Error("--simulate-352 is for dry runs only: apply migration 352 first");
  const cards = JSON.parse(readFileSync(resolve(ROOT, "src/lib/server/university-catalog-reviewed-malaysia.json"), "utf8"));
  const links = JSON.parse(readFileSync(resolve(DATA, "city-links.json"), "utf8"));
  const costFile = readFileSync(resolve(DATA, "programme-costs.json"));
  const plan = planImport(JSON.parse(costFile.toString("utf8")), {
    fileSha256: createHash("sha256").update(costFile).digest("hex"), organizationId: ORGANIZATION_ID,
  });
  if (plan.problems.length > 0) throw new Error(`programme-costs.json invalid: ${plan.problems.slice(0, 5).join("; ")}`);
  if (actorMembership !== null && !UUID.test(actorMembership)) throw new Error("--actor-membership must be a UUID");
  const keys = new Set();
  for (const card of cards) {
    if (keys.has(card.key)) throw new Error(`duplicate card key ${card.key}`);
    keys.add(card.key);
  }
  for (const key of Object.keys(links)) if (!keys.has(key)) throw new Error(`city link for unknown card ${key}`);
  const lines = [];
  const out = (text) => lines.push(text);
  out("\\set ON_ERROR_STOP on");
  out("-- Malaysia 2026-11: universities, city links, programme costs. Generated by scripts/catalog/malaysia-universities-sql.mjs.");
  out("BEGIN;");
  out("SET LOCAL statement_timeout = '600s';");
  if (simulate352) {
    // Dry run before migration 352 reaches the database: the same one-fragment replacement, rolled back with the rest.
    out(`DO $sim$ DECLARE d TEXT; BEGIN d := pg_get_functiondef('platform_private.valid_university_content(jsonb)'::regprocedure);
  IF position('NOT BETWEEN 1 AND 30 THEN' IN d) > 0 THEN EXECUTE replace(d, 'NOT BETWEEN 1 AND 30 THEN', 'NOT BETWEEN 1 AND 300 THEN'); END IF; END $sim$;`);
  }
  out("CREATE TEMP TABLE a_cards (ord INT PRIMARY KEY, key TEXT NOT NULL, city_key TEXT, content JSONB NOT NULL);");
  cards.forEach((card, index) => {
    out(`INSERT INTO a_cards VALUES (${index + 1}, ${dollar(card.key, "k")}, ${links[card.key] ? dollar(links[card.key], "c") : "NULL"}, ${dollar(card.content, "j")}::jsonb);`);
  });
  out("CREATE TEMP TABLE a_report (ord INT, key TEXT, name TEXT, state TEXT, institution_id UUID, version_before BIGINT, version_after BIGINT,");
  out("  programmes INT, programmes_new INT, programmes_changed INT, city_link TEXT);");
  out("CREATE TEMP TABLE a_costs_result (receipt JSONB);");
  out(`SELECT ${actorMembership ? `'${actorMembership}'::uuid` : "m.id"} AS actor_membership, p.auth_user_id AS actor_sub`);
  out("FROM platform.organization_memberships m JOIN platform.profiles p ON p.id = m.profile_id");
  out(`WHERE m.organization_id = '${ORGANIZATION_ID}' AND m.status = 'active' AND p.status = 'active' AND m.is_system_admin`);
  if (actorMembership) out(`  AND m.id = '${actorMembership}'`);
  out("ORDER BY m.created_at LIMIT 1 \\gset");
  // The session claims the Platform reads (platform.current_actor_authority): the user, the membership and the organization.
  out(`SELECT set_config('request.jwt.claims', json_build_object('sub', :'actor_sub', 'role', 'authenticated',
  'platform_membership_id', :'actor_membership', 'platform_organization_id', '${ORGANIZATION_ID}')::text, TRUE) \\g /dev/null`);
  out("SELECT set_config('request.jwt.claim.sub', :'actor_sub', TRUE) \\g /dev/null");
  out(`DO $run$
DECLARE
  org CONSTANT UUID := '${ORGANIZATION_ID}';
  c RECORD; inst UUID; ver BIGINT; old JSONB; st TEXT; digest TEXT; draft JSONB; pub JSONB; link TEXT; n_new INT; n_changed INT;
BEGIN
  FOR c IN SELECT * FROM a_cards ORDER BY ord LOOP
    SELECT i.id INTO inst FROM platform.catalog_institutions i
    WHERE i.organization_id = org AND i.institution_kind = 'university' AND i.country_code = c.content ->> 'country'
      AND platform_private.normalize_catalog_institution_name(i.institution_name) = platform_private.normalize_catalog_institution_name(c.content ->> 'name');
    old := NULL; ver := 0;
    IF inst IS NOT NULL THEN
      SELECT p.version, p.content INTO ver, old FROM platform_private.university_catalog_publications p
      WHERE p.organization_id = org AND p.institution_id = inst AND p.status = 'published' ORDER BY p.version DESC LIMIT 1;
      ver := COALESCE(ver, 0);
    END IF;
    st := CASE WHEN inst IS NULL OR old IS NULL THEN 'new' WHEN old = c.content THEN 'current' ELSE 'update' END;
    SELECT count(*) FILTER (WHERE old IS NULL OR NOT EXISTS (SELECT 1 FROM jsonb_array_elements(old -> 'programs') o WHERE o ->> 'id' = n ->> 'id')),
           count(*) FILTER (WHERE old IS NOT NULL AND EXISTS (SELECT 1 FROM jsonb_array_elements(old -> 'programs') o WHERE o ->> 'id' = n ->> 'id' AND o <> n))
      INTO n_new, n_changed FROM jsonb_array_elements(c.content -> 'programs') n;
    digest := encode(sha256(convert_to(c.content::TEXT, 'UTF8')), 'hex');
    IF st <> 'current' THEN
      EXECUTE 'SET LOCAL ROLE authenticated';
      draft := platform.stage_university_catalog_publication(org, inst, ver, c.content,
        'Каталог Малайзии 2026-11: ' || c.key || '; SHA256 ' || digest,
        md5('evo-my-2611:' || c.key || ':' || ver || ':' || digest || ':stage')::UUID);
      pub := platform.review_university_catalog_publication(org, (draft ->> 'draftId')::UUID, 'publish',
        md5('evo-my-2611:' || c.key || ':' || ver || ':' || digest || ':publish')::UUID);
      EXECUTE 'RESET ROLE';
      inst := (pub ->> 'institutionId')::UUID;
    END IF;
    link := NULL;
    IF c.city_key IS NOT NULL THEN
      SELECT l.city_key INTO link FROM platform.catalog_institution_cities l WHERE l.institution_id = inst;
      IF link IS DISTINCT FROM c.city_key THEN
        EXECUTE 'SET LOCAL ROLE authenticated';
        PERFORM platform.staff_catalog_institution_city_set_v1(org, inst, c.city_key,
          md5('evo-my-2611:' || c.key || ':city:' || c.city_key)::UUID);
        EXECUTE 'RESET ROLE';
        link := c.city_key || ' (set)';
      END IF;
    ELSE
      SELECT l.city_key INTO link FROM platform.catalog_institution_cities l WHERE l.institution_id = inst;
    END IF;
    INSERT INTO a_report VALUES (c.ord, c.key, c.content ->> 'name', st, inst, ver,
      (SELECT COALESCE(max(p.version), 0) FROM platform_private.university_catalog_publications p WHERE p.organization_id = org AND p.institution_id = inst AND p.status = 'published'),
      jsonb_array_length(c.content -> 'programs'), n_new, n_changed, link);
  END LOOP;
END
$run$;`);
  if (!skipCosts) {
    out("CREATE TEMP TABLE a_cost_rows (batch INT PRIMARY KEY, request_id UUID NOT NULL, rows JSONB NOT NULL);");
    plan.batches.forEach((batch, index) => {
      out(`INSERT INTO a_cost_rows VALUES (${index}, '${batch.p_request_id}', ${dollar(batch.p_rows, "r")}::jsonb);`);
    });
    out(`DO $costs$
DECLARE b RECORD; receipt JSONB;
BEGIN
  FOR b IN SELECT * FROM a_cost_rows ORDER BY batch LOOP
    EXECUTE 'SET LOCAL ROLE authenticated';
    receipt := platform.staff_catalog_cost_import_v1('${ORGANIZATION_ID}'::UUID, b.rows, b.request_id);
    EXECUTE 'RESET ROLE';
    INSERT INTO a_costs_result VALUES (jsonb_build_object('created', receipt -> 'created', 'existing', receipt -> 'existing', 'institutionMissing', receipt -> 'institutionMissing'));
  END LOOP;
END
$costs$;`);
  }
  out("-- Report: cards");
  out("SELECT 'CARD', key, state, programmes, programmes_new, programmes_changed, version_before, version_after, COALESCE(city_link, '-') FROM a_report ORDER BY ord;");
  out("SELECT 'SUMMARY_CARDS', count(*) FILTER (WHERE state = 'new'), count(*) FILTER (WHERE state = 'update'), count(*) FILTER (WHERE state = 'current'), sum(programmes), sum(programmes_new), sum(programmes_changed) FROM a_report;");
  if (!skipCosts) {
    out("SELECT 'COSTS_RPC', sum((receipt ->> 'created')::INT), sum((receipt ->> 'existing')::INT), sum((receipt ->> 'institutionMissing')::INT) FROM a_costs_result;");
  }
  out(`-- Report: programmes with and without a published tuition row (per university)
SELECT 'COVERAGE', r.key, count(*) AS programmes,
  count(*) FILTER (WHERE EXISTS (SELECT 1 FROM platform.catalog_costs k WHERE k.organization_id = '${ORGANIZATION_ID}' AND k.institution_id = r.institution_id
    AND k.program_id = p ->> 'id' AND k.cost_kind = 'tuition' AND k.status = 'published')) AS with_cost,
  count(*) FILTER (WHERE p ->> 'level' = 'foundation') AS foundation
FROM a_report r
JOIN LATERAL (SELECT content FROM platform_private.university_catalog_publications q WHERE q.organization_id = '${ORGANIZATION_ID}' AND q.institution_id = r.institution_id AND q.status = 'published' ORDER BY q.version DESC LIMIT 1) latest ON TRUE
CROSS JOIN LATERAL jsonb_array_elements(latest.content -> 'programs') p
GROUP BY r.key, r.ord ORDER BY r.ord;
SELECT 'COVERAGE_TOTAL', count(*), count(*) FILTER (WHERE EXISTS (SELECT 1 FROM platform.catalog_costs k WHERE k.organization_id = '${ORGANIZATION_ID}' AND k.institution_id = r.institution_id
    AND k.program_id = p ->> 'id' AND k.cost_kind = 'tuition' AND k.status = 'published'))
FROM a_report r
JOIN LATERAL (SELECT content FROM platform_private.university_catalog_publications q WHERE q.organization_id = '${ORGANIZATION_ID}' AND q.institution_id = r.institution_id AND q.status = 'published' ORDER BY q.version DESC LIMIT 1) latest ON TRUE
CROSS JOIN LATERAL jsonb_array_elements(latest.content -> 'programs') p;
SELECT 'MY_INSTITUTIONS_AFTER', count(*) FROM platform.catalog_institutions WHERE organization_id = '${ORGANIZATION_ID}' AND country_code = 'MY';`);
  out(commit ? "COMMIT;" : "ROLLBACK;");
  return { sql: `${lines.join("\n")}\n`, cards: cards.length, costRows: plan.summary.rows, requestIds: plan.summary.requestIds };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  let commit = false, actorMembership = null, skipCosts = false, simulate352 = false;
  for (let index = 0; index < args.length; index += 1) {
    if (args[index] === "--commit") commit = true;
    else if (args[index] === "--skip-costs") skipCosts = true;
    else if (args[index] === "--simulate-352") simulate352 = true;
    else if (args[index] === "--actor-membership") actorMembership = args[++index] ?? null;
    else { process.stderr.write("Usage: node scripts/catalog/malaysia-universities-sql.mjs [--commit] [--actor-membership UUID] [--skip-costs] [--simulate-352]\n"); process.exit(1); }
  }
  const result = buildSql({ commit, actorMembership, skipCosts, simulate352 });
  process.stderr.write(`${JSON.stringify({ mode: commit ? "COMMIT" : "ROLLBACK (dry run)", cards: result.cards, costRows: result.costRows })}\n`);
  process.stdout.write(result.sql);
}
