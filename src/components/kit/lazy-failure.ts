/**
 * Отказ ленивого куска «Нового вида» (`lazy`, `next/dynamic`): `.catch(onLazyFailed(заглушка))`. На сервере `import()` может
 * отклониться только из-за ошибки в коде (бросок при загрузке модуля), поэтому там ошибка уходит выше — в `(v3)/error.tsx` и
 * журнал сервера, как на `main`, а не прячется под ответом 200 с заглушкой. В браузере причина обычно в связи (обрыв): нарисованную
 * страницу не снимаем, оставляем заглушку, а ошибку пишем в `console.error`, чтобы ошибка в коде куска не осталась незамеченной.
 * Файл без импортов: его берёт `HelpTip`, который должен оставаться лёгким. Обычная функция, а не стрелка с `<T>`: стенды на Node
 * грузят `.ts` как TSX, где `<T>(…) =>` читается как JSX.
 */
export function onLazyFailed<T>(fallback: T): (error: unknown) => T {
  return (error) => {
    if (typeof window === "undefined") throw error;
    console.error("[Новый вид] не загрузился ленивый кусок экрана:", error);
    return fallback;
  };
}
