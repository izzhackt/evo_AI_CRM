/**
 * Склейка классов строки очереди: каждый класс — целое слово в своей строке-аргументе, а не обрывок шаблона вплотную
 * к интерполяции. Сборщик Tailwind читает только целые слова: `basis-0` перед интерполяцией он не видел, и правило
 * `.basis-0` пропадало из CSS прежнего вида; а приклеенный к интерполяции класс `gap-x-1` для широкой строки задач
 * (с вариантом контейнера) в CSS не попадал никогда, и её зазор всегда был `gap-x-2`. Пустые части отбрасываются; без
 * `tailwind-merge` — порядок и состав классов остаются ровно такими, как написаны. Названия таких классов в комментариях
 * целиком не пишут: сборщик читает и комментарии.
 */
export function joinClasses(...parts: readonly string[]): string {
  return parts.filter(Boolean).join(" ");
}
